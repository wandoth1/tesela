<#
.SYNOPSIS
  Builds Tesela's MSI installer (per-user or per-machine, with UI), portable zip, and SHA256SUMS.txt, then validates the
  result.

.DESCRIPTION
  All inputs come from scripts/build-release.ps1 (static CRT, --remap-path-prefix, exact executable set, local value
  scan, and PE imports): this script runs it first (unless -SkipBuild) and packages EXACTLY those two executables plus
  LICENSE-MIT, LICENSE-APACHE, and THIRD-PARTY-NOTICES.md.

  Tool: WiX Toolset $WixVersion (`wix` CLI, `dotnet tool`; MS-RL; used to compile only, not redistributed). Install it
  once with `pwsh -File scripts/install-wix.ps1 -Version 5.0.2` (uses installer/nuget.config, nuget.org only, and checks
  the package SHA-512); uninstall it with `dotnet tool uninstall --global wix`. The version is PINNED here, in ci.yml,
  and in release.yml (scripts/tests/wix-version.tests.ps1 checks that all three match); the script rejects other versions.
  (Version 5.0.2 is pinned instead of 6.x/7.x because version 6 introduced the OSMF agreement, which must be accepted;
  5.0.2 is MS-RL and requires no acceptance.)

  Output (in -OutDir, default <Cargo target>/dist; nothing is written to the repository):
      tesela-<version>-x64.msi
      tesela-<version>-x64-portable.zip
      SHA256SUMS.txt

  MSI validation (fails if anything is unexpected):
    * `wix msi validate` (ICE); only ICE61 (AllowSameVersionUpgrades) and ICE57 for the two shortcut components are accepted
      (see $AcceptedIce).
    * read-only Windows Installer API table checks (scripts/msi-validate.ps1): version, UpgradeCode, dual scope
      (ALLUSERS=2, MSIINSTALLPERUSER=1, and the Summary Information bit allowing installation without elevation), exactly
      the five expected files, only the expected type-51 and type-35 custom actions, registration only under
      HKMU\Software\Tesela, directory tree, two shortcuts (Start menu and desktop), icon, secure properties, MajorUpgrade,
      blocks on older versions and scope changes, and the UI (dialogs, native events, Spanish and English text).
    * the MSI's files (extracted with `wix msi decompile -x`) are byte-for-byte equal to the build outputs.
    * leak scan (user, computer, profile, repository, CARGO_HOME, and toolchain) of the MSI, each contained file, each file
      in the EXTRACTED zip, and zip entry names. Raw MSI and zip bytes are compressed and cannot be searched directly;
      their extracted contents are scanned as well.

.PARAMETER OutDir
  Output directory (created if needed). Only the three files generated by this script are overwritten, using their exact
  names. It uses its own temporary `_work` subdirectory (refuses to continue if it already exists) and removes it on exit.

.PARAMETER SkipBuild
  Does not call build-release.ps1; uses existing release binaries (for local iteration only; rejected in GitHub Actions).

.PARAMETER Version
  FOR LOCAL UPGRADE TESTS ONLY: overrides the MSI version and filenames (e.g. 0.1.1 to test that a new version replaces
  the previous one). Executables retain the Cargo.toml version. Rejected in GitHub Actions: a release ALWAYS uses the
  Cargo.toml version.

.EXAMPLE
  pwsh -File scripts/build-msi.ps1
#>
[CmdletBinding()]
param(
    [string]$OutDir,
    [switch]$SkipBuild,
    [string]$Version
)

$ErrorActionPreference = 'Stop'

# --- Constants (changing these requires deliberate consideration) --------------------------------------------------------
$WixVersion = '5.0.2'
# ICE warnings that are ACCEPTED (any other warning is a failure). Each entry has a line pattern and rationale.
#   * ICE61: AllowSameVersionUpgrades="yes" (reinstalling the SAME version replaces the existing one) means the replacement
#     row's maximum version is not less than the product version. This is intentional.
#   * ICE57 only for StartMenuShortcut and DesktopShortcut: a shortcut is per-user data and its KeyPath is an HKMU value
#     (HKCU per-user, HKLM per-machine), which ICE57 cannot resolve. This is the standard design for a dual-purpose package
#     (the shortcut and its KeyPath always belong to the same user or machine context).
$AcceptedIce = @(
    @{ Pattern = ': warning WIX1076: ICE61: This product should remove only older versions of itself\. The Maximum version is not less than the current product\.' },
    @{ Pattern = ": error WIX0204: ICE57: Component '(StartMenuShortcut|DesktopShortcut)' has both per-user data and a keypath that can be either per-user or per-machine\.$" }
)

. (Join-Path $PSScriptRoot 'leak-scan.ps1')
. (Join-Path $PSScriptRoot 'msi-validate.ps1')
$ExpectedFiles = $MsiExpectedFiles

function Write-Step([string]$Text) { Write-Host "build-msi: $Text" }

function Invoke-Native {
    # Run a program and return its output lines; fail unless its exit code is 0 or explicitly allowed.
    param([string]$Exe, [string[]]$Arguments, [int[]]$OkCodes = @(0))
    $out = & $Exe @Arguments 2>&1 | ForEach-Object { "$_" }
    if ($OkCodes -notcontains $LASTEXITCODE) {
        $out | ForEach-Object { Write-Host "  $_" }
        throw "$([System.IO.Path]::GetFileName($Exe)) exited with code $LASTEXITCODE"
    }
    return , @($out)
}

function Get-FileSha256([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

# --- Start ----------------------------------------------------------------------------------------------------------------
$repo = (& git rev-parse --show-toplevel).Trim()
    if ($LASTEXITCODE -ne 0 -or -not $repo) { throw 'could not locate the repository (git rev-parse)' }
$workCreated = $false
Push-Location $repo
try {
    if ($SkipBuild -and $env:GITHUB_ACTIONS -eq 'true') { throw '-SkipBuild is for local iteration only: GitHub Actions always builds the release' }
    $meta = & cargo metadata --format-version 1 --no-deps | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
    $versions = @($meta.packages | ForEach-Object { $_.version } | Sort-Object -Unique)
    if ($versions.Count -ne 1) { throw "workspace crates do not share a version: $($versions -join ', ')" }
    $cargoVersion = $versions[0]
    $msiVersion = $cargoVersion
    if ($Version) {
        if ($env:GITHUB_ACTIONS -eq 'true') { throw '-Version is for local testing only: releases use the Cargo.toml version' }
        $msiVersion = $Version
        Write-Host "build-msi: WARNING: -Version $Version is for local upgrade tests only (executables use $cargoVersion). Do not publish this." -ForegroundColor Yellow
    }
    if ($msiVersion -notmatch '^(\d+)\.(\d+)\.(\d+)$' -or [int]$Matches[1] -gt 255 -or [int]$Matches[2] -gt 255 -or [int]$Matches[3] -gt 65535) {
        throw "version '$msiVersion' does not fit in an MSI (numeric major.minor.build; no suffixes such as -rc1)"
    }

    # WiX at the pinned version.
    $wix = Get-Command wix -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $wix) {
        throw "'wix' was not found. Install it with: pwsh -File scripts/install-wix.ps1 -Version $WixVersion"
    }
    $wixOut = (Invoke-Native $wix.Source @('--version')) -join ' '
    if (-not $wixOut.StartsWith("$WixVersion+") -and $wixOut.Trim() -ne $WixVersion) {
        throw "WiX '$wixOut': this repository pins $WixVersion (dotnet tool uninstall --global wix; pwsh -File scripts/install-wix.ps1 -Version $WixVersion)"
    }
    Write-Step "WiX $wixOut"

    $targetDir = $meta.target_directory
    if (-not $OutDir) { $OutDir = Join-Path $targetDir 'dist' }
    $OutDir = [System.IO.Path]::GetFullPath($OutDir)
    New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
    # Only touch files generated by this script, using their EXACT names (never delete anything else in -OutDir).
    $msiName = "tesela-$msiVersion-x64.msi"
    $zipName = "tesela-$msiVersion-x64-portable.zip"
    $msiPath = Join-Path $OutDir $msiName
    $zipPath = Join-Path $OutDir $zipName
    foreach ($f in @($msiPath, $zipPath, (Join-Path $OutDir 'SHA256SUMS.txt'))) {
        if (Test-Path -LiteralPath $f) { Remove-Item -LiteralPath $f -Force }
    }
    $work = Join-Path $OutDir '_work'
    if (Test-Path -LiteralPath $work) { throw "already exists: $work (left by another run or an unrelated directory); remove it manually or use another -OutDir" }
    New-Item -ItemType Directory -Path $work | Out-Null
    $workCreated = $true

    # --- 1. Release (the only source of executables) --------------------------------------------------------------------
    if (-not $SkipBuild) {
        Write-Step 'scripts/build-release.ps1'
        $self = (Get-Process -Id $PID).MainModule.FileName
        & $self -NoProfile -File (Join-Path $PSScriptRoot 'build-release.ps1')
        if ($LASTEXITCODE -ne 0) { throw 'build-release.ps1 failed' }
    }
    $releaseDir = Join-Path $targetDir 'release'
    $exes = @('tesela.exe', 'tesela-scan.exe')
    foreach ($e in $exes) {
        if (-not (Test-Path -LiteralPath (Join-Path $releaseDir $e) -PathType Leaf)) { throw "missing $e in the release directory (run build-release.ps1)" }
    }
    # Executables carry the Cargo.toml version in VERSIONINFO.
    foreach ($e in $exes) {
        $pv = (Get-Item -LiteralPath (Join-Path $releaseDir $e)).VersionInfo.ProductVersion
        if ($pv -ne $cargoVersion) { throw "$e has version '$pv' but Cargo.toml says '$cargoVersion' (stale build: run build-release.ps1)" }
    }

    # --- 2. Prepare package contents (the same five files for the MSI and zip) -----------------------------------------
    $stage = Join-Path $work 'stage'
    New-Item -ItemType Directory -Force -Path $stage | Out-Null
    foreach ($e in $exes) { Copy-Item -LiteralPath (Join-Path $releaseDir $e) -Destination $stage }
    foreach ($d in 'LICENSE-MIT', 'LICENSE-APACHE', 'THIRD-PARTY-NOTICES.md') { Copy-Item -LiteralPath (Join-Path $repo $d) -Destination $stage }
    $stagedNames = @(Get-ChildItem -LiteralPath $stage -File | ForEach-Object { $_.Name })
    foreach ($n in $ExpectedFiles) { if ($stagedNames -notcontains $n) { throw "missing $n from staged contents" } }
    if ($stagedNames.Count -ne $ExpectedFiles.Count) { throw "staged contents have extra files: $($stagedNames -join ', ')" }

    $py = Get-Command python -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $py) { $py = Get-Command python3 -ErrorAction SilentlyContinue | Select-Object -First 1 }
    if (-not $py) { throw 'Python 3 is required on PATH (scripts/extract-ico.py)' }
    $ico = Join-Path $work 'tesela.ico'
    Invoke-Native $py.Source @('-I', (Join-Path $repo 'scripts/extract-ico.py'), (Join-Path $stage 'tesela.exe'), $ico) | ForEach-Object { Write-Host "  $_" }

    # --- 3. MSI ---------------------------------------------------------------------------------------------------------
    Write-Step "wix build -> $msiName"
    $buildOut = Invoke-Native $wix.Source @(
        'build', (Join-Path $repo 'installer/Tesela.wxs'), (Join-Path $repo 'installer/TeselaUI.wxs'), '-arch', 'x64', '-nologo', '-wx',
        '-d', "Version=$msiVersion", '-d', "SourceDir=$stage", '-d', "IconFile=$ico",
        '-pdbtype', 'none', '-o', $msiPath)
    $buildOut | ForEach-Object { if ($_) { Write-Host "  $_" } }

    # --- 4. Validate the MSI ---------------------------------------------------------------------------------------------
    Write-Step 'wix msi validate (ICE)'
    $iceOut = & $wix.Source msi validate $msiPath 2>&1 | ForEach-Object { "$_" }
    $iceCode = $LASTEXITCODE
    $bad = New-Object System.Collections.Generic.List[string]
    $acceptedErrors = 0
    foreach ($line in $iceOut) {
        if (-not $line.Trim()) { continue }
        $accepted = $false
        foreach ($i in $AcceptedIce) { if ($line.TrimEnd() -match $i.Pattern) { $accepted = $true } }
        if ($accepted) {
            if ($line -match ' error ') { $acceptedErrors++ }
            Write-Host "  (accepted) $($line.Substring([Math]::Max(0, $line.IndexOf('warning'))))"
        } else { $bad.Add($line) }
    }
    # A non-zero exit code is tolerated only when explained by ACCEPTED warnings that ICE reports as errors (ICE57 for the
    # shortcuts); any other cause, or an empty diagnostic, is a failure.
    # ... and only when there are EXACTLY the two expected warnings (the shortcut components).
    if (($iceCode -ne 0 -and $acceptedErrors -ne 2) -or $bad.Count -gt 0) {
        $bad | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
        throw "wix msi validate: exit code $iceCode, $($bad.Count) unaccepted messages"
    }

    Write-Step 'MSI tables (Windows Installer, read-only)'
    $problems = Test-MsiPackage -Path $msiPath -ExpectedVersion $msiVersion
    if ($problems.Count -gt 0) {
        $problems | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
        throw 'MSI does not meet the expected checks'
    }

    Write-Step 'MSI contents against build outputs'
    $extract = Join-Path $work 'msi-files'
    Invoke-Native $wix.Source @('msi', 'decompile', '-x', $extract, '-o', (Join-Path $work 'decompiled.wxs'), $msiPath) | Out-Null
    $mapping = @{
        'TeselaExe' = 'tesela.exe'; 'TeselaScanExe' = 'tesela-scan.exe'; 'LicenseMit' = 'LICENSE-MIT'
        'LicenseApache' = 'LICENSE-APACHE'; 'ThirdPartyNotices' = 'THIRD-PARTY-NOTICES.md'
    }
    $inMsi = @(Get-ChildItem -LiteralPath (Join-Path $extract 'File') -File)
    if ($inMsi.Count -ne $ExpectedFiles.Count) { throw "MSI contains $($inMsi.Count) files; expected $($ExpectedFiles.Count)" }
    foreach ($f in $inMsi) {
        $name = $mapping[$f.Name]
        if (-not $name) { throw "unexpected file in MSI: $($f.Name)" }
        if ((Get-FileSha256 $f.FullName) -ne (Get-FileSha256 (Join-Path $stage $name))) { throw "$name in MSI does not match the build output" }
    }

    # --- 5. Zip portable -------------------------------------------------------------------------------------------------
    Write-Step "zip portable -> $zipName"
    Add-Type -AssemblyName System.IO.Compression
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $rootInZip = "tesela-$msiVersion-x64-portable"
    $zip = [System.IO.Compression.ZipFile]::Open($zipPath, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
        foreach ($n in $ExpectedFiles) {
            [void][System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, (Join-Path $stage $n), "$rootInZip/$n", [System.IO.Compression.CompressionLevel]::Optimal)
        }
    } finally {
        $zip.Dispose()
    }

    # --- 6. Local value leaks: MSI, MSI contents, zip contents, and entry names -----------------------------------------
    Write-Step 'scan for local values (MSI, zip, and extracted contents)'
    $cargoHome = $env:CARGO_HOME
    if (-not $cargoHome) { $cargoHome = Join-Path $env:USERPROFILE '.cargo' }
    $sysroot = (& rustc --print sysroot).Trim()
    $rustupHome = $env:RUSTUP_HOME
    if (-not $rustupHome) { $rustupHome = Join-Path $env:USERPROFILE '.rustup' }
    $needles = Get-LocalValueNeedles -Repo $repo -CargoHome $cargoHome -Sysroot $sysroot -RustupHome $rustupHome
    $leaks = New-Object System.Collections.Generic.List[string]
    foreach ($l in (Find-LocalValueLeaks -Bytes ([System.IO.File]::ReadAllBytes($msiPath)) -Needles $needles -Name $msiName)) { $leaks.Add($l) }
    foreach ($f in $inMsi) {
        foreach ($l in (Find-LocalValueLeaks -Bytes ([System.IO.File]::ReadAllBytes($f.FullName)) -Needles $needles -Name "$msiName/$($mapping[$f.Name])")) { $leaks.Add($l) }
    }
    foreach ($l in (Find-LocalValueLeaks -Bytes ([System.IO.File]::ReadAllBytes($ico)) -Needles $needles -Name "$msiName/icono")) { $leaks.Add($l) }
    $zipRead = [System.IO.Compression.ZipFile]::OpenRead($zipPath)
    try {
        $entryNames = @($zipRead.Entries | ForEach-Object { $_.FullName })
        $expectedEntries = @($ExpectedFiles | ForEach-Object { "$rootInZip/$_" })
        if ($entryNames.Count -ne $expectedEntries.Count -or @($entryNames | Where-Object { $expectedEntries -notcontains $_ }).Count -gt 0) {
            throw "zip does not contain exactly the expected files: $($entryNames -join ', ')"
        }
        foreach ($l in (Find-LocalValueLeaks -Bytes ([System.Text.Encoding]::UTF8.GetBytes(($entryNames -join "`n"))) -Needles $needles -Name "$zipName (nombres)")) { $leaks.Add($l) }
        foreach ($entry in $zipRead.Entries) {
            $ms = New-Object System.IO.MemoryStream
            $s = $entry.Open()
            try { $s.CopyTo($ms) } finally { $s.Dispose() }
            $bytes = $ms.ToArray()
            foreach ($l in (Find-LocalValueLeaks -Bytes $bytes -Needles $needles -Name "$zipName/$($entry.FullName)")) { $leaks.Add($l) }
            $leaf = $entry.FullName.Substring($rootInZip.Length + 1)
            if ((Get-FileSha256 (Join-Path $stage $leaf)) -ne ([System.BitConverter]::ToString([System.Security.Cryptography.SHA256]::Create().ComputeHash($bytes)).Replace('-', '').ToLowerInvariant())) {
                throw "$leaf in zip does not match the build output"
            }
        }
    } finally {
        $zipRead.Dispose()
    }
    if ($leaks.Count -gt 0) {
        Write-Host 'build-msi: packages contain data from this machine:' -ForegroundColor Red
        $leaks | Sort-Object -Unique | ForEach-Object { Write-Host "  $_" }
        throw 'local value leak'
    }

    # --- 7. Checksums ----------------------------------------------------------------------------------------------------
    $sums = @($msiPath, $zipPath) | ForEach-Object { '{0}  {1}' -f (Get-FileSha256 $_), (Split-Path -Leaf $_) }
    [System.IO.File]::WriteAllText((Join-Path $OutDir 'SHA256SUMS.txt'), (($sums -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))

    Write-Host ''
    Write-Host ('build-msi: {0}: {1:N0} bytes ({2:N2} MiB)' -f $msiName, (Get-Item -LiteralPath $msiPath).Length, ((Get-Item -LiteralPath $msiPath).Length / 1MB))
    Write-Host ('build-msi: {0}: {1:N0} bytes ({2:N2} MiB)' -f $zipName, (Get-Item -LiteralPath $zipPath).Length, ((Get-Item -LiteralPath $zipPath).Length / 1MB))
    Write-Host "build-msi: SHA256SUMS.txt:"
    $sums | ForEach-Object { Write-Host "  $_" }
    Write-Host "build-msi: OK ($OutDir)"
} catch {
    Write-Host "build-msi: ERROR: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
} finally {
    if ($workCreated -and (Test-Path -LiteralPath $work)) { Remove-Item -LiteralPath $work -Recurse -Force }
    Pop-Location
}
